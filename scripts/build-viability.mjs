// Builds site/shared/data/viability.js (daily mean VIABILITY per missionID group + total VIABILITY per site) from:
//   docs/fLandingSites_viability.csv  LANDINGSITEID,DATE,VIABILITY
//   site/shared/data/dLandingSites.csv  ID,NAME,LAT,LONG,missionID,...
//   docs/dMission.csv                  ID,NAME,OBJECTIVES  (ID = missionID; names the groups)
// Usage: node scripts/build-viability.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8').trim().split(/\r?\n/).slice(1).map((l) => l.split(','));

// OBJECTIVES may contain commas only if quoted; these files have none, so keep the plain split but join the tail.
const missions = new Map(readFileSync(new URL('docs/dMission.csv', root), 'utf8').trim().split(/\r?\n/).slice(1)
  .map((l) => l.split(',')).map(([id, name, ...objectives]) => [Number(id), { name: name.trim(), objectives: objectives.join(',').trim() }]));
const groupOf = new Map(read('site/shared/data/dLandingSites.csv').map((c) => [c[0], Number(c[4])]));
const dates = new Set();
const sums = new Map(); // group -> Map(date -> [sum, count])
const siteTotals = new Map(); // site id -> sum of VIABILITY over every day
for (const [site, date, value] of read('docs/fLandingSites_viability.csv')) {
  const g = groupOf.get(site);
  const v = Number(value);
  if (g === undefined || !/^\d{4}-\d{2}-\d{2}$/.test(date) || !Number.isFinite(v)) throw new Error(`invalid row: ${site},${date},${value}`);
  dates.add(date);
  siteTotals.set(site, (siteTotals.get(site) || 0) + v);
  if (!sums.has(g)) sums.set(g, new Map());
  const acc = sums.get(g).get(date) || [0, 0];
  sums.get(g).set(date, [acc[0] + v, acc[1] + 1]);
}

const days = [...dates].sort();
// Days must be consecutive: the chart uses the day index as x.
days.forEach((d, i) => {
  const expected = new Date(Date.parse(days[0] + 'T00:00:00Z') + i * 86400000).toISOString().slice(0, 10);
  if (d !== expected) throw new Error(`dia faltando: esperado ${expected}, veio ${d}`);
});

const groups = [...sums.keys()].sort((a, b) => a - b).map((g) => ({
  group: g,
  name: missions.has(g) ? missions.get(g).name : `Group ${g}`,
  objectives: missions.has(g) ? missions.get(g).objectives : '',
  sites: [...groupOf].filter(([, gg]) => gg === g).map(([id]) => Number(id)),
  mean: days.map((d) => {
    const s = sums.get(g).get(d);
    if (!s) throw new Error(`group ${g} has no data on ${d}`);
    return Math.round((s[0] / s[1]) * 10) / 10;
  })
}));

const out = '// Generated by scripts/build-viability.mjs from docs/fLandingSites_viability.csv — do not edit by hand.\n' +
  '(typeof window !== \'undefined\' ? window : globalThis).MoonViability = ' + JSON.stringify({ start: days[0], days: days.length, groups, siteTotals: Object.fromEntries([...siteTotals].map(([k, v]) => [k, Math.round(v * 100) / 100])) }) + ';\n';
writeFileSync(new URL('site/shared/data/viability.js', root), out);
console.log(`viability.js: ${groups.length} groups x ${days.length} days (${days[0]}..${days.at(-1)}), ${out.length} bytes`);
